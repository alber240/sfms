let currentLang = localStorage.getItem('sfms_lang') || 'en';

function switchLanguage(langCode) {
    currentLang = langCode;
    localStorage.setItem('sfms_lang', langCode);
    translatePage();
    
    // Update dropdown
    const dropdown = document.getElementById('langSelect');
    if (dropdown) dropdown.value = langCode;
}

function translatePage() {
    // Translate elements with data-translate attribute
    document.querySelectorAll('[data-translate]').forEach(el => {
        const key = el.getAttribute('data-translate');
        if (translations[currentLang][key]) {
            if (el.tagName === 'INPUT' && el.placeholder) {
                el.placeholder = translations[currentLang][key];
            } else if (el.tagName === 'BUTTON' || el.tagName === 'A') {
                // Preserve icons if present
                const icon = el.querySelector('.icon');
                if (icon) {
                    el.innerHTML = icon.outerHTML + ' ' + translations[currentLang][key];
                } else {
                    el.textContent = translations[currentLang][key];
                }
            } else {
                el.textContent = translations[currentLang][key];
            }
        }
    });
    
    // Translate page title
    const title = document.querySelector('title');
    if (title && translations[currentLang][title.textContent]) {
        title.textContent = translations[currentLang][title.textContent];
    }
}

// Auto-translate on page load
document.addEventListener('DOMContentLoaded', function() {
    translatePage();
});
