        for receipt in receipts:
            ws.cell(row=row, column=1, value=receipt.receipt_number)
            ws.cell(row=row, column=2, value=receipt.student.full_name)
            ws.cell(row=row, column=3, value=receipt.student.admission_number)
            ws.cell(row=row, column=4, value=float(receipt.amount_lrd))
            ws.cell(row=row, column=5, value=float(receipt.amount_usd))
            ws.cell(row=row, column=6, value=str(receipt.payment_date))
            ws.cell(row=row, column=7, value=receipt.get_payment_method_display())
            ws.cell(row=row, column=8, value=receipt.get_payment_period_display())
            ws.cell(row=row, column=9, value=receipt.mobile_transaction_id or '')
            ws.cell(row=row, column=10, value=receipt.academic_year)
            ws.cell(row=row, column=11, value='Voided' if receipt.is_voided else 'Active')
            
            total_lrd += receipt.amount_lrd
            total_usd += receipt.amount_usd
            row += 1
        
        # Add totals row
        row += 1
        ws.cell(row=row, column=3, value="TOTAL:").font = Font(bold=True)
        ws.cell(row=row, column=4, value=float(total_lrd)).font = Font(bold=True)
        ws.cell(row=row, column=5, value=float(total_usd)).font = Font(bold=True)
        
        self._auto_width(ws)
        return wb
    
