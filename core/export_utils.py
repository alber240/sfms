        wb = Workbook()
        ws = wb.active
        ws.title = "Receipts"
        
        subtitle = f"Academic Year: {academic_year}" if academic_year else "All Receipts"
        row = self._add_title(ws, "SFMS - Payment Receipts", subtitle)
        
        headers = [
            'Receipt #', 'Student', 'Admission #', 'Amount LRD', 'Amount USD',
            'Payment Date', 'Method', 'Period', 'Mobile Trans ID',
            'Academic Year', 'Status'
        ]
